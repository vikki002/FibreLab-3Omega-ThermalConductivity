import queue as _queue

# The GUI thread must never write to the DSP7265 directly while a
# measurement is running — the measurement thread is talking to the same
# GPIB resource continuously, and two threads issuing commands at once can
# corrupt each other's reads/writes and crash the run. Instead, the GUI
# enqueues requested setting changes here, and the measurement thread (the
# sole owner of GPIB access during a run) drains and applies them at safe
# points inside its own polling loops.
LOCKIN7265_CMD_QUEUE = _queue.Queue()

def _drain_lockin7265_queue():
    while True:
        try:
            action, value = LOCKIN7265_CMD_QUEUE.get_nowait()
        except _queue.Empty:
            break
        try:
            if action == "voltage":
                lockin7265.voltage = value
            elif action == "frequency":
                lockin7265.frequency = value
            elif action == "write":
                lockin7265.write(value)
        except Exception as e:
            print(f"7265 queued command error ({action}, {value}): {e}")

