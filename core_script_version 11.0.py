def calibrate_1w_phase(callback=None, freq=5.0, wait_time=300, average_time=60,
                       auto_params_fn=None,
                       auto_sens_sr830=False, auto_sens_7265=False,
                       stability_check_fn=None,
                       sr830_thresholds_fn=None, dsp7265_thresholds_fn=None):
    """Measure 1ω signal at freq, wait for stability, average R and θ, then write
    PHAS {avg_theta} to SR830 so circuit phase is removed from subsequent 3ω measurements.
    Returns (avg_r, avg_theta, avg_theta), or (None, None, None) if stopped early.
    Callback phase: '1w_time': (t_data, r_data, theta_data, wait_n)
    """
    # Always clear skip flag on entry and exit so a stale flag never carries over
    sys.modules[__name__].__dict__['skip_1w_calib'] = False
    try:
      return _calibrate_1w_phase_inner(callback=callback, freq=freq,
                                       wait_time=wait_time, average_time=average_time,
                                       auto_params_fn=auto_params_fn,
                                       auto_sens_sr830=auto_sens_sr830,
                                       auto_sens_7265=auto_sens_7265,
                                       stability_check_fn=stability_check_fn,
                                       sr830_thresholds_fn=sr830_thresholds_fn,
                                       dsp7265_thresholds_fn=dsp7265_thresholds_fn)
    finally:
      sys.modules[__name__].__dict__['skip_1w_calib'] = False


def _calibrate_1w_phase_inner(callback=None, freq=5.0, wait_time=300, average_time=60,
                               auto_params_fn=None,
                               auto_sens_sr830=False, auto_sens_7265=False,
                               stability_check_fn=None,
                               sr830_thresholds_fn=None, dsp7265_thresholds_fn=None):
    setup_lockin_w()           # HARM 1, same voltage / TC / sensitivity as 3ω setup
    setup_lockin_7265_3w()     # configure DSP7265 (harmonic already = 1)
    lockin.write(f"FREQ {freq}")
    lockin7265.frequency = freq

    if auto_params_fn is not None:
        try:
            auto_params_fn(freq)
        except Exception:
            pass

    time.sleep(STABILIZATION_TIME)

    t_start    = time.time()
    t_data     = []
    r_data     = []
    theta_data = []
    i_data     = []   # AC current from DSP7265 (A)

    # stability window = last 20% of wait_time (in samples)
    STAB_WINDOW   = max(15, int(0.20 * wait_time / dt))
    max_wait_time = wait_time * 3
    t_wait_start  = time.time()

    # Always track current 7265 sensitivity index for current conversion.
    # Overwritten inside the auto_sens block when auto_sens_7265 is True.
    sens_idx_7265 = LOCKIN_7265_SENS

    # ── Adaptive stability-polling wait ───────────────────────────────────────
    if auto_sens_sr830 or auto_sens_7265:
        if auto_sens_sr830:
            sens_idx = LOCKIN_SENS
            lockin.write(f"SENS {sens_idx}")
            globals()['LOCKIN_SENS'] = sens_idx
            sr830_buf          = []
            sr830_settle_until = 0.0
            sr830_stepped_up   = False
            sr830_prev_idx     = sens_idx
            _tc_sr830 = _SR830_TC_VALUES[min(int(LOCKIN_OFLT), len(_SR830_TC_VALUES)-1)]
            sr830_phase1_end   = time.time() + max(_tc_sr830, 3.0 * dt)
            sr830_in_phase1    = True
            print(f"  1ω SR830 adaptive wait — SENS {sens_idx} "
                  f"({_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV)...")

        if auto_sens_7265:
            lockin7265.write("AUTOMATIC 0")          # disable hardware auto-gain
            sens_idx_7265 = LOCKIN_7265_SENS
            lockin7265.write(f"SEN {sens_idx_7265}")
            globals()['LOCKIN_7265_SENS'] = sens_idx_7265
            dsp_buf          = []
            dsp_settle_until = 0.0
            dsp_stepped_up   = False
            dsp_prev_idx     = sens_idx_7265
            _tc_dsp7265 = _DSP7265_TC_VALUES[min(int(LOCKIN_7265_TC), len(_DSP7265_TC_VALUES)-1)]
            dsp_phase1_end   = time.time() + max(_tc_dsp7265, 3.0 * dt)
            dsp_in_phase1    = True
            print(f"  1ω DSP7265 adaptive wait — SEN {sens_idx_7265} "
                  f"({_DSP7265_SENS_VALUES[sens_idx_7265]*1e6:.3g} µV)...")

        # Clear any stale force_averaging flag from a previous run before
        # entering the wait loop.  The interface also resets this, but doing
        # it here closes a window where the patched sleep (which calls
        # processEvents) could re-process a queued button click before the
        # loop begins.
        sys.modules[__name__].__dict__['force_averaging'] = False

        while True:
            _drain_lockin7265_queue()
            if getattr(sys.modules[__name__], "stop_requested", False):
                return None, None, None
            if getattr(sys.modules[__name__], "skip_1w_calib", False):
                sys.modules[__name__].__dict__['skip_1w_calib'] = False
                return None, None, None
            if getattr(sys.modules[__name__], "force_averaging", False):
                print("  1ω force averaging triggered by user")
                break

            _, _, r, o = map(float, lockin.query("SNAP? 1,2,3,4").strip().split(','))
            MAG_raw = float(lockin7265.ask("MAG"))
            I_AC    = (MAG_raw / 10000.0) * _DSP7265_SENS_VALUES[sens_idx_7265] * CURRENT_CONVERSION_FACTOR
            safety_check(I_AC, r)

            t_data.append(time.time() - t_start)
            r_data.append(r)
            theta_data.append(o)
            i_data.append(I_AC)

            if callback:
                callback('1w_time', t_data, r_data, theta_data, None, i_data)

            _sr830_ol, _sr830_low, _sr830_stab = (sr830_thresholds_fn() if sr830_thresholds_fn else (0.90, 0.10, 0.005))
            _dsp_ol,   _dsp_low,   _dsp_stab   = (dsp7265_thresholds_fn() if dsp7265_thresholds_fn else (0.90, 0.10, 0.005))

            # ── SR830 auto-range (two-phase) ──────────────────────────────
            if auto_sens_sr830:
                _tc_sr830 = _SR830_TC_VALUES[min(int(LOCKIN_OFLT), len(_SR830_TC_VALUES)-1)]
                _fs_sr    = _SR830_SENS_VALUES[sens_idx]
                _hw_ol = False
                try:
                    _hw_ol = bool(int(lockin.query("LIAS?").strip()) & 0x04)  # bit2 = OUTPT overload
                except Exception:
                    pass

                if sr830_in_phase1:
                    # Phase 1: rapid coarse hunt — no blanking, step immediately
                    if time.time() >= sr830_phase1_end:
                        sr830_in_phase1 = False   # timer expired, hand off to phase 2
                    else:
                        if _hw_ol or r > _sr830_ol * _fs_sr:
                            _ni = min(sens_idx + 1, len(_SR830_SENS_VALUES) - 1)
                            if _ni != sens_idx:
                                sens_idx = _ni
                                lockin.write(f"SENS {sens_idx}")
                                globals()['LOCKIN_SENS'] = sens_idx
                                sr830_buf.clear()
                                print(f"    SR830 [P1] SENS → {_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV")
                        elif r < _sr830_low * _fs_sr:
                            _ni = max(sens_idx - 1, 0)
                            if _ni != sens_idx:
                                sens_idx = _ni
                                lockin.write(f"SENS {sens_idx}")
                                globals()['LOCKIN_SENS'] = sens_idx
                                sr830_buf.clear()
                                print(f"    SR830 [P1] SENS → {_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV")

                if not sr830_in_phase1:
                    # Phase 2: 3 TC confirmation state machine
                    if sr830_stepped_up:
                        # Monitoring window after stepping to more sensitive
                        if r < _sr830_low * _fs_sr:
                            # Still below 10% — step again immediately
                            sr830_prev_idx = sens_idx
                            _ni = max(sens_idx - 1, 0)
                            if _ni != sens_idx:
                                sens_idx = _ni
                                lockin.write(f"SENS {sens_idx}")
                                globals()['LOCKIN_SENS'] = sens_idx
                                sr830_settle_until = time.time() + 3.0 * _tc_sr830
                                sr830_buf.clear()
                                print(f"    SR830 [P2] SENS → {_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV")
                        elif time.time() >= sr830_settle_until:
                            # 3 TC elapsed — check if still overloaded
                            if _hw_ol or r > _sr830_ol * _fs_sr:
                                # Overloaded after 3 TC → step back to less sensitive
                                sens_idx = sr830_prev_idx
                                lockin.write(f"SENS {sens_idx}")
                                globals()['LOCKIN_SENS'] = sens_idx
                                sr830_settle_until = time.time() + 3.0 * _tc_sr830
                                sr830_stepped_up = False
                                sr830_buf.clear()
                                print(f"    SR830 [P2] overloaded after 3TC → {_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV")
                            else:
                                # Settled in range — optimal found
                                sr830_stepped_up = False
                                sr830_buf.append(r)
                    else:
                        if time.time() >= sr830_settle_until:
                            if _hw_ol or r > _sr830_ol * _fs_sr:
                                # Overloaded → step to less sensitive
                                _ni = min(sens_idx + 1, len(_SR830_SENS_VALUES) - 1)
                                if _ni != sens_idx:
                                    sens_idx = _ni
                                    lockin.write(f"SENS {sens_idx}")
                                    globals()['LOCKIN_SENS'] = sens_idx
                                    sr830_settle_until = time.time() + 3.0 * _tc_sr830
                                    sr830_buf.clear()
                                    print(f"    SR830 [P2] SENS → {_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV")
                            elif r < _sr830_low * _fs_sr:
                                # Below 10% → step to more sensitive
                                sr830_prev_idx = sens_idx
                                _ni = max(sens_idx - 1, 0)
                                if _ni != sens_idx:
                                    sens_idx = _ni
                                    lockin.write(f"SENS {sens_idx}")
                                    globals()['LOCKIN_SENS'] = sens_idx
                                    sr830_settle_until = time.time() + 3.0 * _tc_sr830
                                    sr830_stepped_up = True
                                    sr830_buf.clear()
                                    print(f"    SR830 [P2] SENS → {_SR830_SENS_VALUES[sens_idx]*1e6:.3g} µV")
                            else:
                                sr830_buf.append(r)
                                if len(sr830_buf) > STAB_WINDOW:
                                    sr830_buf.pop(0)

            # ── DSP7265 auto-range (two-phase) ────────────────────────────
            if auto_sens_7265:
                _tc_dsp7265 = _DSP7265_TC_VALUES[min(int(LOCKIN_7265_TC), len(_DSP7265_TC_VALUES)-1)]
                _frac = MAG_raw / 10000.0

                if dsp_in_phase1:
                    # Phase 1: rapid coarse hunt — no blanking, step immediately
                    if time.time() >= dsp_phase1_end:
                        dsp_in_phase1 = False
                    else:
                        if _frac > _dsp_ol:
                            _ni = min(sens_idx_7265 + 1, 27)
                            if _ni != sens_idx_7265:
                                sens_idx_7265 = _ni
                                lockin7265.write(f"SEN {sens_idx_7265}")
                                globals()['LOCKIN_7265_SENS'] = sens_idx_7265
                                dsp_buf.clear()
                                print(f"    DSP7265 [P1] SEN → {sens_idx_7265}")
                        elif _frac < _dsp_low:
                            _ni = max(sens_idx_7265 - 1, 1)
                            if _ni != sens_idx_7265:
                                sens_idx_7265 = _ni
                                lockin7265.write(f"SEN {sens_idx_7265}")
                                globals()['LOCKIN_7265_SENS'] = sens_idx_7265
                                dsp_buf.clear()
                                print(f"    DSP7265 [P1] SEN → {sens_idx_7265}")

                if not dsp_in_phase1:
                    # Phase 2: 3 TC confirmation state machine
                    if dsp_stepped_up:
                        if _frac < _dsp_low:
                            dsp_prev_idx = sens_idx_7265
                            _ni = max(sens_idx_7265 - 1, 1)
                            if _ni != sens_idx_7265:
                                sens_idx_7265 = _ni
                                lockin7265.write(f"SEN {sens_idx_7265}")
                                globals()['LOCKIN_7265_SENS'] = sens_idx_7265
                                dsp_settle_until = time.time() + 3.0 * _tc_dsp7265
                                dsp_buf.clear()
                                print(f"    DSP7265 [P2] SEN → {sens_idx_7265}")
                        elif time.time() >= dsp_settle_until:
                            if _frac > _dsp_ol:
                                sens_idx_7265 = dsp_prev_idx
                                lockin7265.write(f"SEN {sens_idx_7265}")
                                globals()['LOCKIN_7265_SENS'] = sens_idx_7265
                                dsp_settle_until = time.time() + 3.0 * _tc_dsp7265
                                dsp_stepped_up = False
                                dsp_buf.clear()
                                print(f"    DSP7265 [P2] overloaded after 3TC → SEN {sens_idx_7265}")
                            else:
                                dsp_stepped_up = False
                                dsp_buf.append(MAG_raw)
                    else:
                        if time.time() >= dsp_settle_until:
                            if _frac > _dsp_ol:
                                _ni = min(sens_idx_7265 + 1, 27)
                                if _ni != sens_idx_7265:
                                    sens_idx_7265 = _ni
                                    lockin7265.write(f"SEN {sens_idx_7265}")
                                    globals()['LOCKIN_7265_SENS'] = sens_idx_7265
                                    dsp_settle_until = time.time() + 3.0 * _tc_dsp7265
                                    dsp_buf.clear()
                                    print(f"    DSP7265 [P2] SEN → {sens_idx_7265}")
                            elif _frac < _dsp_low:
                                dsp_prev_idx = sens_idx_7265
                                _ni = max(sens_idx_7265 - 1, 1)
                                if _ni != sens_idx_7265:
                                    sens_idx_7265 = _ni
                                    lockin7265.write(f"SEN {sens_idx_7265}")
                                    globals()['LOCKIN_7265_SENS'] = sens_idx_7265
                                    dsp_settle_until = time.time() + 3.0 * _tc_dsp7265
                                    dsp_stepped_up = True
                                    dsp_buf.clear()
                                    print(f"    DSP7265 [P2] SEN → {sens_idx_7265}")
                            else:
                                dsp_buf.append(MAG_raw)
                                if len(dsp_buf) > STAB_WINDOW:
                                    dsp_buf.pop(0)

            elapsed = time.time() - t_wait_start

            STAB_WINDOW = max(15, int(0.20 * wait_time / dt))

            sr830_stable = True
            if auto_sens_sr830:
                if elapsed >= wait_time and len(sr830_buf) >= STAB_WINDOW:
                    mean_r = np.mean(sr830_buf)
                    sr830_stable = (mean_r > 0 and
                                    (max(sr830_buf) - min(sr830_buf)) / mean_r < _sr830_stab)
                else:
                    sr830_stable = False

            dsp_stable = True
            if auto_sens_7265:
                if elapsed >= wait_time and len(dsp_buf) >= STAB_WINDOW:
                    mean_m = np.mean(dsp_buf)
                    dsp_stable = (mean_m > 0 and
                                  (max(dsp_buf) - min(dsp_buf)) / mean_m < _dsp_stab)
                else:
                    dsp_stable = False

            if sr830_stable and dsp_stable:
                print(f"  1ω stable after {elapsed:.0f}s")
                break

            if elapsed >= max_wait_time:
                if stability_check_fn is not None:
                    decision = stability_check_fn(elapsed, freq)
                    if decision == 'proceed':
                        break
                    elif isinstance(decision, str) and decision.startswith('wait:'):
                        max_wait_time += float(decision.split(':')[1])
                else:
                    break

            time.sleep(dt)

    else:
        # ── Fixed wait ────────────────────────────────────────────────────────
        sys.modules[__name__].__dict__['force_averaging'] = False
        t_fixed = time.time()
        while (time.time() - t_fixed) < wait_time:
            _drain_lockin7265_queue()
            if getattr(sys.modules[__name__], "stop_requested", False):
                return None, None, None
            if getattr(sys.modules[__name__], "skip_1w_calib", False):
                sys.modules[__name__].__dict__['skip_1w_calib'] = False
                return None, None, None
            if getattr(sys.modules[__name__], "force_averaging", False):
                print("  1ω force averaging triggered by user")
                break
            _, _, r, o = map(float, lockin.query("SNAP? 1,2,3,4").strip().split(','))
            MAG_raw = float(lockin7265.ask("MAG"))
            I_AC    = (MAG_raw / 10000.0) * _DSP7265_SENS_VALUES[LOCKIN_7265_SENS] * CURRENT_CONVERSION_FACTOR
            safety_check(I_AC, r)
            t_data.append(time.time() - t_start)
            r_data.append(r)
            theta_data.append(o)
            i_data.append(I_AC)
            if callback:
                callback('1w_time', t_data, r_data, theta_data, None, i_data)
            time.sleep(dt)

    wait_n = len(t_data)

    # ── Averaging phase ───────────────────────────────────────────────────────
    print(f"  Averaging 1ω signal for {average_time}s...")
    avg_r_vals     = []
    avg_theta_vals = []
    avg_i_vals     = []
    t_avg_start    = time.time()

    while (time.time() - t_avg_start) < average_time:
        _drain_lockin7265_queue()
        if getattr(sys.modules[__name__], "stop_requested", False):
            return None, None, None
        if getattr(sys.modules[__name__], "skip_1w_calib", False):
            sys.modules[__name__].__dict__['skip_1w_calib'] = False
            return None, None, None
        _, _, r, o = map(float, lockin.query("SNAP? 1,2,3,4").strip().split(','))
        MAG_raw = float(lockin7265.ask("MAG"))
        I_AC    = (MAG_raw / 10000.0) * _DSP7265_SENS_VALUES[sens_idx_7265] * CURRENT_CONVERSION_FACTOR
        safety_check(I_AC, r)
        t_data.append(time.time() - t_start)
        r_data.append(r)
        theta_data.append(o)
        i_data.append(I_AC)
        if callback:
            callback('1w_time', t_data, r_data, theta_data, wait_n, i_data)
        avg_r_vals.append(r)
        avg_theta_vals.append(o)
        avg_i_vals.append(I_AC)
        time.sleep(dt)

    avg_r     = float(np.mean(avg_r_vals))
    avg_theta = float(np.mean(avg_theta_vals))
    avg_i     = float(np.mean(avg_i_vals)) if avg_i_vals else 0.0
    avg_res   = avg_r / avg_i if abs(avg_i) > 1e-15 else float('nan')

    # Write calibrated phase to SR830 — persists until overwritten
    lockin.write(f"PHAS {avg_theta:.4f}")
    print(f"  1ω calibration complete — R₁ω = {avg_r*1e3:.4f} mV, PHAS set to {avg_theta:.4f}°")

    return avg_r, avg_theta, avg_res


def IV_measurement(callback=None, iv_wait_time=30, iv_average_time=10,
                   auto_params_fn=None,
                   auto_sens_sr830=False, auto_sens_7265=False,
                   stability_check_fn=None,
                   sr830_thresholds_fn=None, dsp7265_thresholds_fn=None,
                   frequencies=None, freq_wait_map=None,
                   voltages=None):

    IV_DT = 0.2   # polling interval (s) — same as 3ω measurement

    # Build the list of frequencies to sweep. If caller supplies a list, use
    # it; otherwise fall back to the single freq_IV global (legacy behaviour).
    if frequencies is not None and len(frequencies) > 0:
        _iv_freqs = list(frequencies)
    else:
        _iv_freqs = [freq_IV]

    IV_results = []
    sys.modules[__name__].partial_IV_results = []

    # Use caller-supplied voltage list; fall back to legacy globals for backwards compat.
    if voltages is not None and len(voltages) > 0:
        voltages = list(voltages)
    else:
        voltages = list(np.arange(V_start, V_end, step))
    print(f"[IV] {len(voltages)} voltage steps: {[round(v,6) for v in voltages]}")

    # Continuous time-series buffers — shared across ALL frequencies and voltage
    # steps so the saved CSV has a single unbroken time axis.
    t_iv_start  = time.time()
    t_iv_data   = []
    v3w_iv_data = []

    # One full voltage sweep per frequency
    for _cur_freq in _iv_freqs:
        globals()['freq_IV'] = _cur_freq   # keep global in sync for setup fns

        setup_lockin_IV()
        lockin.write(f"SLVL {voltages[0]}")  # pre-set to sweep start before wait/setup phase

        setup_lockin_7265_IV()

        if auto_params_fn is not None:
            try:
                auto_params_fn(_cur_freq)
            except Exception:
                pass

        print(f"Ready for IV measurement at {_cur_freq:.4g} Hz")

        # Per-frequency wait time: freq_wait_map overrides iv_wait_time
        _iv_wt = iv_wait_time
        if freq_wait_map:
            _iv_wt = freq_wait_map.get(round(_cur_freq, 9), iv_wait_time)

        # Auto-sens: tracks settled SENS indices across voltage steps
        last_sens_idx_iv      = LOCKIN_SENS
        last_sens_idx_iv_7265 = LOCKIN_7265_SENS

        I3_IV   = []
        V3w_IV  = []

        for v in voltages:

            # 🔴 STOP CHECK #1 (before new voltage step)
            if getattr(sys.modules[__name__], "stop_requested", False):
                print("IV stopped by user")
                return IV_results

            print(f"Setting voltage: {v}")
            lockin.write(f"SLVL {v}")

            # Index where this voltage step's data begins
            v_start_idx = len(t_iv_data)
            label       = f"{v*1000:.2f} mV"

            # =================================================================
            # WAIT PHASE
            # =================================================================
            if auto_sens_sr830 or auto_sens_7265:
                # Adaptive stability-polling wait (SR830 and/or DSP7265)
                # Reset force_averaging at the start of each voltage step's wait
                sys.modules[__name__].__dict__['force_averaging'] = False
                IV_STAB_WINDOW = max(15, int(0.20 * _iv_wt / IV_DT))
                iv_max_wait    = _iv_wt * 3
                t_iv_wait_start = time.time()

                if auto_sens_sr830:
                    sens_idx_iv    = last_sens_idx_iv
                    lockin.write(f"SENS {sens_idx_iv}")
                    globals()['LOCKIN_SENS'] = sens_idx_iv
                    iv_sr830_buf          = []
                    iv_sr830_settle_until = 0.0
                    iv_sr830_stepped_up   = False
                    iv_sr830_prev_idx     = sens_idx_iv
                    _tc_sr830_iv  = _SR830_TC_VALUES[min(int(LOCKIN_OFLT), len(_SR830_TC_VALUES)-1)]
                    iv_sr830_phase1_end = time.time() + max(_tc_sr830_iv, 3.0 * IV_DT)
                    iv_sr830_in_phase1  = True

                if auto_sens_7265:
                    lockin7265.write("AUTOMATIC 0")
                    sens_idx_iv_7265  = last_sens_idx_iv_7265
                    lockin7265.write(f"SEN {sens_idx_iv_7265}")
                    globals()['LOCKIN_7265_SENS'] = sens_idx_iv_7265
                    iv_dsp_buf          = []
                    iv_dsp_settle_until = 0.0
                    iv_dsp_stepped_up   = False
                    iv_dsp_prev_idx     = sens_idx_iv_7265
                    _tc_dsp7265_iv = _DSP7265_TC_VALUES[min(int(LOCKIN_7265_TC), len(_DSP7265_TC_VALUES)-1)]
                    iv_dsp_phase1_end = time.time() + max(_tc_dsp7265_iv, 3.0 * IV_DT)
                    iv_dsp_in_phase1  = True

                while True:
                    _drain_lockin7265_queue()
                    if getattr(sys.modules[__name__], "stop_requested", False):
                        print("Stopped during IV stabilization")
                        return IV_results
                    if getattr(sys.modules[__name__], "force_averaging", False):
                        print("  IV force averaging triggered by user")
                        break

                    x, y, r, o = map(float, lockin.query("SNAP? 1,2,3,4").strip().split(','))
                    MAG_raw_iv = float(lockin7265.ask("MAG"))
                    v3w        = np.sqrt(x**2 + y**2)
                    _sen_idx_now_iv = int(lockin7265.ask("SEN"))
                    _I_AC_now_iv = (MAG_raw_iv / 10000.0) * _DSP7265_SENS_VALUES[_sen_idx_now_iv] * CURRENT_CONVERSION_FACTOR
                    safety_check(_I_AC_now_iv, v3w)

                    t_iv_data.append(time.time() - t_iv_start)
                    v3w_iv_data.append(v3w)
                    if callback:
                        callback('iv_time', t_iv_data, v3w_iv_data,
                                 v_start_idx, None, label)

                    _iv_sr830_ol, _iv_sr830_low, _iv_sr830_stab = (
                        sr830_thresholds_fn() if sr830_thresholds_fn else (0.90, 0.10, 0.005))
                    _iv_dsp_ol, _iv_dsp_low, _iv_dsp_stab = (
                        dsp7265_thresholds_fn() if dsp7265_thresholds_fn else (0.90, 0.10, 0.005))

                    if auto_sens_sr830:
                        _tc_sr830_iv = _SR830_TC_VALUES[min(int(LOCKIN_OFLT), len(_SR830_TC_VALUES)-1)]
                        _fs_sr_iv    = _SR830_SENS_VALUES[sens_idx_iv]
                        _hw_ol_iv = False
                        try:
                            _hw_ol_iv = bool(int(lockin.query("LIAS?").strip()) & 0x04)  # bit2 = OUTPT overload
                        except Exception:
                            pass

                        if iv_sr830_in_phase1:
                            if time.time() >= iv_sr830_phase1_end:
                                iv_sr830_in_phase1 = False
                            else:
                                if _hw_ol_iv or r > _iv_sr830_ol * _fs_sr_iv:
                                    _ni = min(sens_idx_iv + 1, len(_SR830_SENS_VALUES) - 1)
                                    if _ni != sens_idx_iv:
                                        sens_idx_iv = _ni
