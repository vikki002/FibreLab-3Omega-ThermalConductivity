# 1. LOW-FREQUENCY METHOD
# =========================================================
def compute_k_lowfreq(dataset, A, f_min=None, f_max=None):

    data = np.array(dataset)

    freqs = data[:, 0]
    v3w   = data[:, 5]
    Irms   = data[:, 1]  

    # ---- STRICT RANGE SELECTION ----
    if f_min is None or f_max is None:
        raise ValueError("You MUST provide both f_min and f_max")

    mask = (freqs >= f_min) & (freqs <= f_max)

    if np.sum(mask) < 2:
        raise ValueError("Not enough points in selected range")

    freqs_sel = freqs[mask]
    v3w_sel   = v3w[mask]
    I_sel     = Irms[mask]

    v_mean = np.mean(v3w_sel)
    v_std  = np.std(v3w_sel, ddof=1)
    N      = len(v3w_sel)
    v_sem  = v_std / np.sqrt(N)

    I_mean = np.mean(I_sel)
    I_std  = np.std(I_sel, ddof=1)
    I_sem  = I_std / np.sqrt(len(I_sel)) #standard error of mean

    k = A * I_mean**3 / v_mean

    # propagate relative errors
    k_err = k * np.sqrt((3 * I_sem / I_mean)**2 + (v_sem / v_mean)**2)

    print("\n===== LOW-FREQUENCY METHOD =====")
    print(f"Used ONLY: {f_min} – {f_max} Hz")
    print(f"Mean V3ω = {v_mean:.3e} ± {v_sem:.3e} V")
    print(f"Mean I = {I_mean:.3e} ± {I_sem:.3e} A")
    print(f"k_mean (Low frequency limit) = {k:.4f} ± {k_err:.4f} W/mK")

    return k


