def setup_lockin_7265_3w():
    print("Configuring lock-in amplifier 7265 for 3w measurement...")

    lockin7265.write("INT")                           # internal reference oscillator

    lockin7265.voltage  = AC_VOLTAGE_7265             # OA — oscillator amplitude
    lockin7265.harmonic = 1                           # REFN — harmonic number
    lockin7265.write("REFP 0")                        # REFP — reference phase (millidegrees, 0 = 0°)

    lockin7265.write(f"IMODE {LOCKIN_7265_IMODE}")   # input mode (voltage / current)
    lockin7265.write(f"VMODE {LOCKIN_7265_VMODE}")   # voltage input channel (A / A-B)
    lockin7265.write(f"FLOAT {LOCKIN_7265_FLOAT}")   # input shield float/ground
    lockin7265.write(f"CP {LOCKIN_7265_CP}")         # input coupling (AC/DC)

    lockin7265.write(f"LF {LOCKIN_7265_LF}")         # line frequency rejection

    lockin7265.write("AUTOMATIC 0")                  # software-controlled gain (hunt used instead)

    lockin7265.write(f"SEN {LOCKIN_7265_SENS}")      # SEN — starting sensitivity index
    lockin7265.write(f"TC {LOCKIN_7265_TC}")         # TC  — time constant index
    lockin7265.write(f"SLOPE {LOCKIN_7265_SLOPE}")   # output filter slope


