def shutdown():
    print("Shutting down safely...")
    try:
        n_steps = 10
        delay   = 0.2

        current_slvl = float(lockin.query("SLVL?"))
        if current_slvl > MIN_VOLTAGE:
            for v in np.linspace(current_slvl, MIN_VOLTAGE, n_steps):
                lockin.write(f"SLVL {v:.6f}")
                time.sleep(delay)
        else:
            lockin.write(f"SLVL {MIN_VOLTAGE}")

        current_freq = float(lockin.query("FREQ?"))
        if current_freq > 1.0:
            for f in np.linspace(current_freq, 1.0, n_steps):
                lockin.write(f"FREQ {f:.4f}")
                time.sleep(delay)
        else:
            lockin.write("FREQ 1")

        lockin.write("HARM 1")
    except:
        pass

    try:
        current_slvl_7265 = float(lockin7265.voltage)
        if current_slvl_7265 > MIN_VOLTAGE_7265:
            for v in np.linspace(current_slvl_7265, MIN_VOLTAGE_7265, n_steps):
                lockin7265.voltage = v
                time.sleep(delay)
        else:
            lockin7265.voltage = MIN_VOLTAGE_7265

        current_freq_7265 = float(lockin7265.frequency)
        if current_freq_7265 > 1.0:
            for f in np.linspace(current_freq_7265, 1.0, n_steps):
                lockin7265.frequency = f
                time.sleep(delay)
        else:
            lockin7265.frequency = 1.0

        lockin7265.harmonic = 1
    except:
        pass

