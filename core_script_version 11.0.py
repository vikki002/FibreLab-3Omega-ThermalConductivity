def fit_3omega_fixed_A(dataset, A, f_min, f_max):

    data = np.array(dataset)

    freqs = data[:, 0]
    v3w   = data[:, 5]
    Irms  = data[:, 1] 

    # ---- STRICT RANGE ----
    mask = (freqs >= f_min) & (freqs <= f_max)

    if np.sum(mask) < 3:
        raise ValueError("Need at least 3 points for fitting")

    freqs_fit = freqs[mask]
    v3w_fit   = v3w[mask]
    I_fit     = Irms[mask]


    print("\n===== FIT METHOD =====")
    print(f"Fitting ONLY: {f_min} – {f_max} Hz")
    # print(f"Points used: {len(freqs_fit)}")

    # ---- MODEL ----
    def model(x, k, gamma):
        freq, I = x
        return (A*I**3)/ (k * np.sqrt(1 + (4 * np.pi * freq * gamma)**2))

    # ---- INITIAL GUESSES ----
    k_guess = (A*np.mean(I_fit)**3) / np.mean(v3w_fit)   # smart guess
    gamma_guess = 1e-3

    popt, pcov = curve_fit(
        model,
        (freqs_fit, I_fit),
        v3w_fit,
        p0=[k_guess, gamma_guess],
        maxfev=10000
    )

    k_fit, gamma_fit = popt
    k_err         = np.sqrt(pcov[0, 0])
    gamma_fit_err = np.sqrt(pcov[1, 1])

    if not np.isfinite(k_err) or not np.isfinite(gamma_fit_err):
        raise ValueError(
            f"Fit converged but covariance is ill-conditioned (k_err={k_err}, γ_err={gamma_fit_err}). "
            "Try a narrower or better-sampled frequency range."
        )

    print(f"Thermal conductivity k = {k_fit:.4f} ± {k_err:.4f} W/mK")
    print(f"Gamma = {gamma_fit:.4e} ± {gamma_fit_err:.4e}")
    print(f"k_err = {k_err:.4f} W/mK")

    v_fit = model((freqs_fit, I_fit), k_fit, gamma_fit)

    # Plotting is handled by the interface — returns raw arrays for the interface to plot.
    # plt.figure(figsize=(7,5))
    # plt.scatter(freqs, v3w, label="All data")
    # plt.scatter(freqs_fit, v3w_fit, color='red', label="Fit region")
    # plt.plot(freqs_fit, v_fit, linewidth=2, label="Fit")
    # plt.axvspan(f_min, f_max, alpha=0.2, label="Fit window")
    # plt.xlabel("Frequency (Hz)")
    # plt.ylabel("V3ω (V)")
    # plt.title("3ω Fit (STRICT RANGE)")
    # plt.legend()
    # plt.grid(True)
    # plt.show()

    return k_fit, gamma_fit, k_err, gamma_fit_err, freqs_fit, v3w_fit, v_fit

#fitting function for the phase to extract the thermal time constant 

def phase_fit(dataset, f_min=None, f_max=None):
 
    data = np.array(dataset)
 
    freqs = data[:, 0]
    phi   = data[:, 6]   # degrees from your dataset
 
    # ---- STRICT RANGE SELECTION ----
    if f_min is None or f_max is None:
        raise ValueError("You MUST provide both f_min and f_max")
 
    mask = (freqs >= f_min) & (freqs <= f_max)
 
    if np.sum(mask) < 3:
        raise ValueError("Need at least 3 points for fitting")
 
    freqs_sel = freqs[mask]
    phi_sel   = phi[mask]
 
    #  convert degrees → radians
    phi_sel = np.deg2rad(phi_sel)
 
    # Use |tan(phi)| so the slope and gamma are always positive regardless of
    # the sign convention of phi (phi can be negative or positive depending on
    # the measurement setup — taking absolute value keeps the fit robust).
    tan_phi = np.abs(np.tan(phi_sel))
 
    # ---- LINEAR FIT WITH COVARIANCE ----
    coeffs, cov = np.polyfit(freqs_sel, tan_phi, 1, cov=True)
 
    slope, intercept = coeffs
    slope_err = np.sqrt(cov[0, 0])   # standard error of slope
 
    # ---- EXTRACT GAMMA ----
    gamma = slope / (4 * np.pi)
    gamma_err = slope_err / (4 * np.pi)
 
    print("\n===== PHASE FIT =====")
    print(f"Fitting range: {f_min} – {f_max} Hz")
    print(f"Gamma = {gamma:.4e} ± {gamma_err:.4e}")
 
    # Plotting handled by the interface — returns raw arrays for plotting.
    # plt.figure(figsize=(6,4))
    # plt.scatter(freqs_sel, tan_phi, label="Data")
    # plt.plot(freqs_sel, slope*freqs_sel + intercept, label="Linear fit")
    # plt.xlabel("Frequency (Hz)")
    # plt.ylabel("tan(phi)")
    # plt.legend()
    # plt.grid(True)
    # plt.show()

    return gamma, gamma_err, freqs_sel, tan_phi, slope, intercept


