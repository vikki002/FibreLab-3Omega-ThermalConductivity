def safety_check(current, voltage):
    if SAFETY_CURRENT_SOURCE == "low":
        if abs(current) > CURRENT_LIMIT:
            print("Current exceeded safe limit!")
            shutdown()
            raise RuntimeError(f"Safety stop: current {current:.4f} A exceeded limit {CURRENT_LIMIT} A")

        if abs(voltage) > VOLTAGE_LIMIT:
            print("Voltage exceeded safe limit!")
            shutdown()
            raise RuntimeError(f"Safety stop: voltage {voltage:.4f} V exceeded limit {VOLTAGE_LIMIT} V")

    else:  # "high" current source — CURRENT_LIMIT is live-set per selected range
        if abs(current) > CURRENT_LIMIT:
            print("Current exceeded safe limit!")
            shutdown()
            raise RuntimeError(
                f"Safety stop: current {current:.6f} A exceeded limit {CURRENT_LIMIT} A "
                f"(high current source, {SAFETY_CURRENT_RANGE})")

        if abs(voltage) >= VOLTAGE_LIMIT_HIGH_SOURCE:
            print("Voltage exceeded safe limit!")
            shutdown()
            raise RuntimeError(
                f"Safety stop: voltage {voltage:.4f} V reached/exceeded limit "
                f"{VOLTAGE_LIMIT_HIGH_SOURCE} V (high current source)")


